#!/usr/bin/env python3
"""Rasterize the bundled Apache-2.0 Open Sans into native UI coverage runs."""
from pathlib import Path
import hashlib
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "third_party/open-sans/OpenSans-Semibold.ttf"
OUTPUT = ROOT / "src/keyboard_font_data.h"


def main():
    font = ImageFont.truetype(str(FONT), 32)
    boxes = [font.getbbox(chr(code), anchor="ls") for code in range(32, 127)]
    top, bottom = min(box[1] for box in boxes), max(box[3] for box in boxes)
    height = bottom - top
    glyphs, runs = [], []
    for code in range(32, 127):
        advance = round(font.getlength(chr(code)) * 64)
        canvas = Image.new("L", (math.ceil(advance / 64) + 4, height))
        ImageDraw.Draw(canvas).text((0, -top), chr(code), font=font, fill=255, anchor="ls")
        first = len(runs)
        active, rectangles = {}, []
        for y in range(height):
            levels = [(canvas.getpixel((x, y)) * 15 + 127) // 255 for x in range(canvas.width)]
            x = 0
            current = {}
            while x < len(levels):
                end = x + 1
                while end < len(levels) and levels[end] == levels[x]:
                    end += 1
                if levels[x]:
                    key = (x, end - x, levels[x])
                    if key in active:
                        rectangle = active[key]
                        rectangle[3] += 1
                    else:
                        rectangle = [x, y, end - x, 1, levels[x]]
                        rectangles.append(rectangle)
                    current[key] = rectangle
                x = end
            active = current
        runs.extend(sorted(rectangles, key=lambda r: (r[1], r[0])))
        glyphs.append((first, len(runs) - first, advance))
    text = [
        "// Generated by scripts/generate-keyboard-font.py; do not edit.",
        "// Open Sans Semibold: Copyright 2010-2011 Google Corporation; Apache-2.0.",
        f"// Font SHA-256: {hashlib.sha256(FONT.read_bytes()).hexdigest()}",
        "#pragma once", "#include <array>", "#include <cstdint>",
        "namespace motogp::prompts::font {",
        "struct Run {uint8_t x,y,width,height,coverage;};",
        "struct Glyph {uint16_t first,count,advance;};",
        f"inline constexpr float kHeight={height}.f;",
        "inline constexpr std::array<Glyph,95> kGlyphs{{",
        *[f"  {{{a},{b},{c}}}," for a, b, c in glyphs], "}};",
        f"inline constexpr std::array<Run,{len(runs)}> kRuns{{{{",
        *[f"  {{{x},{y},{w},{h},{c}}}," for x, y, w, h, c in runs],
        "}};", "}", "",
    ]
    assert len(runs) < 65536
    OUTPUT.write_text("\n".join(text))
    print(f"Generated {len(glyphs)} glyphs / {len(runs)} coverage runs, {OUTPUT.stat().st_size} bytes")


if __name__ == "__main__":
    main()
