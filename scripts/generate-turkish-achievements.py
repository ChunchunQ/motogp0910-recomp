#!/usr/bin/env python3
"""Generate the small shared native/launcher achievement translation table."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
rows=json.loads((root/'resources/localization/tr/achievements.json').read_text())
assert len(rows)==50 and len({r['id'] for r in rows})==50
quote=lambda s:json.dumps(s,ensure_ascii=False)
text='''// Generated by scripts/generate-turkish-achievements.py; edit the JSON catalog.
#pragma once
#include <rex/system/achievement_store.h>
namespace motogp::localization {
inline bool TranslateAchievement(rex::system::AchievementInfo& info){
  struct Text {uint32_t id;const char* label;const char* description;const char* locked;};
  static constexpr Text rows[]={
'''
for r in rows:text+='    {'+str(r['id'])+','+','.join(quote(r[k]) for k in ('tr','description_tr','locked_tr'))+'},\n'
text+='''  };
  for(const auto& row:rows)if(row.id==info.id){info.label=row.label;info.description=row.description;info.unachieved_description=row.locked;return true;}
  return false;
}
}
'''
(root/'src/turkish_achievements.h').write_text(text,encoding='utf-8')
